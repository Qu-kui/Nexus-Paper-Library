/* End-to-end: isolated server + headless Edge, no user browser profile or remote LLM. */
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, dirname, join, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import net from 'node:net';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dependencies = process.env.PAPERWHALE_NODE_MODULES || 'C:/Users/10498/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules';
const require = createRequire(join(dependencies, 'package.json'));
const { chromium } = require('playwright');
const temp = mkdtempSync(join(tmpdir(), 'pw-reader-ui-'));
const listener = net.createServer();
await new Promise(resolve => listener.listen(0, '127.0.0.1', resolve));
const port = listener.address().port;
await new Promise(resolve => listener.close(resolve));
const base = `http://127.0.0.1:${port}`;
let logs = '';
const server = spawn(join(root,'.venv/Scripts/python.exe'), [join(root,'tests/ai_ui_server.py'), String(port)], {
  cwd:root, windowsHide:true, env:{...process.env, PAPERWHALE_UI_TEST:'1', PAPERWHALE_DATA:temp, PAPERWHALE_LLM_MOCK:'1'},
  stdio:['ignore','pipe','pipe'],
});
server.stdout.on('data', chunk => { logs += chunk; });
server.stderr.on('data', chunk => { logs += chunk; });
let browser;
try {
  let ready = false;
  for (let i=0; i<100; i++) {
    try { ready = (await fetch(base+'/api/health')).ok; } catch {}
    if (ready) break;
    if (server.exitCode !== null) throw new Error(logs);
    await new Promise(resolve => setTimeout(resolve,100));
  }
  assert.ok(ready, logs);
  browser = await chromium.launch({ executablePath:process.env.PAPERWHALE_EDGE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless:true });
  const page = await browser.newPage({ viewport:{width:1500,height:1000} });
  const errors = [];
  page.on('pageerror', err => errors.push(err.message));
  await page.addInitScript(() => localStorage.setItem('pw-setup-dismissed','1'));
  await page.goto(base);
  await page.waitForFunction(() => Boolean(window.PW?.openPaper));
  const open = async id => {
    await page.evaluate(id => window.PW.openPaper(id), id);
    await page.locator('#reader-tabs [data-tab="chat"]').click();
    await page.waitForFunction(() => !document.getElementById('reader-chat-send').disabled);
  };
  await open('a');
  await page.waitForFunction(() => window.PW.readerState.doc && window.PW.readerState.pages.size>2);
  await page.locator('#reader-page-input').fill('3');
  await page.locator('#reader-page-input').press('Enter');
  await page.waitForTimeout(550);
  const pdfViewport = await page.locator('#pdf-scroll').boundingBox();
  await page.mouse.move(pdfViewport.x + pdfViewport.width / 2, pdfViewport.y + pdfViewport.height / 2);
  const beforeZoom = await page.evaluate(() => ({width:window.PW.readerState.pages.get(3).offsetWidth, zoom:window.PW.readerState.zoom, viewportScale:visualViewport.scale}));
  await page.keyboard.down('Control');
  await page.mouse.wheel(0,-100);
  await page.waitForFunction(width=>window.PW.readerState.pages.get(3).offsetWidth>width,beforeZoom.width);
  const zoomedWidth=await page.evaluate(()=>window.PW.readerState.pages.get(3).offsetWidth);
  await page.mouse.wheel(0,40);
  await page.waitForFunction(({width,minimum})=>window.PW.readerState.pages.get(3).offsetWidth<width&&window.PW.readerState.zoom>minimum,{width:zoomedWidth,minimum:beforeZoom.zoom});
  await page.keyboard.up('Control');
  assert.equal(await page.evaluate(()=>visualViewport.scale),beforeZoom.viewportScale);
  const afterZoom=await page.evaluate(()=>({zoom:window.PW.readerState.zoom,top:document.getElementById('pdf-scroll').scrollTop}));
  await page.mouse.wheel(0,80);
  await page.waitForFunction(top=>document.getElementById('pdf-scroll').scrollTop>top,afterZoom.top);
  assert.equal(await page.evaluate(()=>window.PW.readerState.zoom),afterZoom.zoom);
  console.log('PASS Ctrl+wheel resizes the PDF in both directions; regular wheel still scrolls');
  await page.evaluate(()=>{const node=window.PW.readerState.pages.get(3);document.getElementById('pdf-scroll').scrollTop=node.offsetTop-18+node.offsetHeight*.18;});
  await page.waitForTimeout(180);
  await page.locator('#reader-close').click();
  await open('a');
  await page.waitForFunction(() => window.PW.readerState.doc && window.PW.readerState.currentPage===3);
  assert.ok(await page.evaluate(() => window.PW.readerState.zoom>1));
  assert.ok(await page.locator('#reader-tabs [data-tab="chat"]').evaluate(el=>el.classList.contains('active')));
  assert.ok(await page.evaluate(()=>{const node=window.PW.readerState.pages.get(3);const offset=(document.getElementById('pdf-scroll').scrollTop-node.offsetTop+18)/node.offsetHeight;return Math.abs(offset-.18)<.01;}));
  console.log('PASS paper reading page, within-page offset, zoom and active tab restore');
  await page.evaluate(async()=>{const {openReader}=await import('/js/reader.js'); await openReader('a',1);});
  await page.waitForFunction(()=>window.PW.readerState.currentPage===1);
  console.log('PASS explicit citation page one overrides reading memory');
  await page.locator('#reader-sidebar-toggle').click();
  assert.equal(await page.locator('.reader-panel').isVisible(),false);
  await page.locator('#reader-sidebar-toggle').click();
  await page.locator('#reader-fit-mode').selectOption('page');
  assert.equal(await page.evaluate(()=>window.PW.readerState.fitMode),'page');
  const priorWidth=await page.locator('.reader-panel').evaluate(el=>el.getBoundingClientRect().width);
  const grip=await page.locator('.reader-sidebar-resizer').boundingBox();
  await page.mouse.move(grip.x+4,grip.y+100);await page.mouse.down();await page.mouse.move(grip.x-76,grip.y+100);await page.mouse.up();
  assert.ok((await page.locator('.reader-panel').evaluate(el=>el.getBoundingClientRect().width))>priorWidth+50);
  console.log('PASS sidebar drag/collapse and page-fit controls');
  await page.locator('#reader-search').fill('attention');
  await page.locator('#reader-search').press('Enter');
  await page.waitForFunction(()=>!window.PW.readerState.search.busy && window.PW.readerState.search.matches?.length>1);
  const count = await page.evaluate(()=>window.PW.readerState.search.matches.length);
  assert.ok(count>1);
  await page.waitForFunction(()=>document.querySelectorAll('.reader-search-hit').length>0);
  await page.locator('#reader-search-next').click();
  assert.ok((await page.locator('#reader-search-count').innerText()).startsWith('第 2 /'));
  console.log('PASS individual search occurrences, highlight and next navigation');
  // Cancel extraction between awaits; neither completion nor highlights may move a new paper.
  await page.evaluate(()=>{
    const doc=window.PW.readerState.doc, getPage=doc.getPage.bind(doc);
    doc.getPage=async number=>{doc.getPage=getPage;return {getTextContent:()=>new Promise(resolve=>{window.releaseOldSearch=()=>resolve({items:[{str:'STALE_SEARCH'}]});})};};
  });
  await page.locator('#reader-search').fill('STALE_SEARCH');
  await page.locator('#reader-search').press('Enter');
  await page.waitForFunction(()=>!!window.releaseOldSearch);
  await page.locator('#reader-search-cancel').click();
  await open('b');
  await page.waitForFunction(()=>window.PW.readerState.doc && window.PW.readerState.paperId==='b');
  await page.evaluate(()=>window.releaseOldSearch());
  await page.waitForTimeout(100);
  assert.equal(await page.locator('#reader-search').inputValue(),'');
  assert.equal(await page.locator('#reader-search-count').innerText(),'');
  assert.equal(await page.evaluate(()=>window.PW.readerState.currentPage),1);
  console.log('PASS cancelled old search cannot change the next paper');
  await open('a');
  await page.waitForFunction(()=>window.PW.readerState.doc);
  let releaseAnalyze, startedAnalyze;
  const analyzeGate=new Promise(resolve=>{releaseAnalyze=resolve;});
  const analyzeStarted=new Promise(resolve=>{startedAnalyze=resolve;});
  await page.route('**/api/ai/summarize/a',async route=>{startedAnalyze();await analyzeGate;await route.fulfill({json:{summary:'STALE_ANALYSIS'}});});
  await page.locator('#reader-tabs [data-tab="summary"]').click();
  await page.locator('#btn-analyze').click();
  await analyzeStarted;
  await open('b');
  releaseAnalyze();
  await page.waitForTimeout(150);
  assert.ok(!(await page.locator('#reader-summary').innerText()).includes('STALE_ANALYSIS'));
  assert.equal(await page.locator('#btn-analyze').isDisabled(),false);
  await page.unroute('**/api/ai/summarize/a');
  console.log('PASS stale analysis cannot update another paper or its controls');
  await open('a');
  await page.locator('#reader-tabs [data-tab="chat"]').click();
  await page.locator('#reader-chat-input').fill('Answer to store');
  await page.locator('#reader-chat-send').click();
  await page.waitForFunction(()=>!window.PW.readerState.chatSession.busy && window.PW.readerState.chatSession.data.messages.length===2);
  await page.evaluate(async()=>{await fetch('/api/papers/a',{method:'PATCH',headers:{'Content-Type':'application/json'},body:JSON.stringify({notes:'ORIGINAL NOTE'})});});
  await page.locator('.reader-answer-save').last().click();
  await page.waitForFunction(async()=>{const p=await (await fetch('/api/papers/a')).json();return p.notes.includes('ORIGINAL NOTE') && p.notes.length>20;});
  console.log('PASS answer appends to latest paper notes');
  await page.evaluate(()=>{window.PW.readerState.selection={text:'selected text',pageNum:1,rects:[{x:.1,y:.1,w:.2,h:.02}]};document.querySelector('#selection-toolbar [data-action="note"]').click();});
  await page.locator('.reader-note-editor textarea').fill('INLINE NOTE');
  await page.locator('.reader-note-save').click();
  await page.waitForFunction(()=>window.PW.readerState.annotations.some(a=>a.note==='INLINE NOTE'));
  assert.ok((await page.locator('#reader-annotations').innerText()).includes('INLINE NOTE'));
  await page.locator('.reader-note-editor textarea').fill('INLINE NOTE UPDATED');
  await page.locator('.reader-note-save').click();
  await page.waitForFunction(()=>window.PW.readerState.annotations.some(a=>a.note==='INLINE NOTE UPDATED'));
  assert.equal(await page.evaluate(()=>window.PW.readerState.annotations.length),1);
  console.log('PASS inline annotation editor saves, remains editable and updates one annotation');
  // Pull actual in-progress model text through the same session subscription used for streaming.
  await page.locator('#reader-tabs [data-tab="chat"]').click();
  await page.evaluate(()=>{const session=window.PW.readerState.chatSession;session.pending='progress question';session.busy=true;session.progress={stage:'正在生成回答',reasoning:'ACTUAL_MODEL_REASONING',answer:'PARTIAL_ANSWER',state:'running'};session.notify();});
  assert.ok((await page.locator('#reader-chat-messages').innerText()).includes('ACTUAL_MODEL_REASONING'));
  assert.ok((await page.locator('#reader-chat-messages').innerText()).includes('PARTIAL_ANSWER'));
  await page.evaluate(()=>{const session=window.PW.readerState.chatSession;session.pending=null;session.busy=false;session.progress=null;session.notify();});
  console.log('PASS actual reasoning, phase and incremental answer render from session progress');
  await page.locator('#reader-chat-clear').click();
  await page.waitForFunction(()=>window.PW.readerState.chatSession.data.messages.length===0);
  await page.locator('#reader-chat-undo').click();
  await page.waitForFunction(()=>window.PW.readerState.chatSession.data.messages.length===2);
  console.log('PASS clear has an undo that restores this paper conversation');
  await page.setViewportSize({width:850,height:700});
  await page.locator('#reader-sidebar-toggle').click();
  assert.equal(await page.locator('.reader-panel').isVisible(),false);
  assert.ok(await page.locator('#pdf-scroll').evaluate(el=>el.clientWidth>800));
  console.log('PASS narrow window gives PDF full width after collapsing sidebar');
  assert.deepEqual(errors,[]);
} finally {
  if(browser) await browser.close();
  server.kill();
  await new Promise(resolve=>server.once('exit',resolve));
  const safe=resolve(temp);
  assert.ok(safe.startsWith(resolve(tmpdir())+sep));
  rmSync(safe,{recursive:true,force:true});
}

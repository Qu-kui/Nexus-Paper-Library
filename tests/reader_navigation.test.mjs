import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
let m={};
try {m=await import('data:text/javascript;base64,'+Buffer.from(await readFile(new URL('../web/js/reader-navigation.js',import.meta.url))).toString('base64'));}catch{}
assert.equal(typeof m.NavigationHistory,'function','navigation history must exist');
const history=new m.NavigationHistory(2);
const a={page:1,offset:.3},b={page:3,offset:.7},c={page:2,offset:0};
history.record(a,b);
assert.deepEqual(history.back(b),a);
assert.deepEqual(history.forward(a),b);
assert.deepEqual(history.back(b),a);
history.record(a,c);
assert.equal(history.canForward,false,'a new jump discards future history');
assert.equal(history.record(c,c),false,'same destination does not add history');
assert.deepEqual(history.back(c),a);
history.reset();
assert.equal(history.canBack,false);
assert.equal(history.canForward,false);
history.record(a,b);history.record(b,c);history.record(c,{page:4,offset:0});
assert.deepEqual(history.back({page:4,offset:0}),c);
assert.deepEqual(history.back(c),b);
assert.equal(history.back(b),null,'history is bounded');
for(const url of ['javascript:alert(1)','file:///C:/secret','data:text/html,test','https://example.com/\nunsafe',''])assert.equal(m.safePdfLink(url),'');
assert.equal(m.safePdfLink('https://example.com/paper'),'https://example.com/paper');
assert.equal(m.safePdfLink('mailto:author@example.com'),'mailto:author@example.com');
const doc={numPages:4,getDestination:async name=>name==='ref'?[{num:8,gen:0},{name:'XYZ'},0,700,null]:null,getPageIndex:async()=>2};
assert.deepEqual(await m.resolvePdfDestination(doc,'ref'),{page:3,x:0,y:700});
assert.deepEqual(await m.resolvePdfDestination(doc,[1,{name:'Fit'}]),{page:2});
assert.equal(await m.resolvePdfDestination(doc,'missing'),null);
assert.equal(await m.resolvePdfDestination(doc,[9,{name:'Fit'}]),null);
console.log('PASS navigation back/forward positions, bounded history, branch truncation, safe native links and named destinations');
